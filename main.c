#include <stdio.h>
#include <locale.h>
#include <malloc.h>

int main()
{
    setlocale(0,"");
    setlocale(LC_NUMERIC, "C");

    printf("\n--------------------------------------------------------------------------\n");
// Ввод данных и создание двумерной матрицы
    int n;
    do{
        printf("\nВведите размер массива n: ");
        scanf("%d", &n);
        if (n <= 0 || n >= 100){
            printf("\n==========================================================================\n");
            printf("Ошибка: нарушен диапазон входных данных");
            printf("\n==========================================================================\n");
        }
    }while (n <= 0 || n >= 100);

    printf("\n--------------------------------------------------------------------------\n");
    int i, j;
    double* *A;
    A = (double**) malloc(n * sizeof(double*));
    printf("\nВведите элементы массива A:\n");
    for (i = 0; i < n; i++){
        A[i] = (double*) malloc(n * sizeof(double));
        for (j = 0; j < n; j++){
            printf("\nA[%d][%d]: ",i,j);
            scanf("%lf", &A[i][j]);
        }
    }

    printf("\n--------------------------------------------------------------------------\n");
// Вывод введённых данных
    printf("\nВведено n: %d\n", n);
    printf("\nВведён массив A:\n");
    printf(" ___");for (i = 0; i < n; i ++) printf(" _______");
    printf("\n|n\\n|"); for (j = 0; j < n; j++) printf("%4d   |", j);
    printf("\n ---");for (i = 0; i < n; i ++) printf("+-------");
    for (i = 0; i < n; i++){
        printf("\n|%2d |",i);
        for (j = 0; j < n; j++){
            printf("%7.2f|", A[i][j]);
        }
    }
    printf("\n ===");for (i = 0; i < n; i ++) printf(" =======");

    printf("\n\n--------------------------------------------------------------------------\n");
// Обработка и вывод результата

//проверка матрица на нижнего треугольная
    int flag = 1;
    i = 0;
    while (i < n && flag){
        j = i+1;
        while (j < n && flag){
            if (A[i][j] != 0) flag = 0;
            else j++;
        }
        i++;
    }
    if (flag){
        printf("\n==========================================================================\n");
        printf("матрица нижнего треугольного");
        printf("\n==========================================================================\n");
    }else{
        printf("\n==========================================================================\n");
        printf("матрица не подходит по условию");
        printf("\n==========================================================================\n");
    }

//находим макс
    if (flag){
        int id_i_max = 0, id_j_max = 0;
        double max = A[0][0];
        for (i = 0; i < n; i++){
            for (j = 0; j<=i;j++){
                if (A[i][j] >= max){
                    max = A[i][j];
                    id_i_max = i;
                    id_j_max = j;
                }
            }
        }
        printf("\n==========================================================================\n");
        printf("\n\t\tРезультат:\n");
        printf("\nМакс: A[%d][%d] = %.2lf\n", id_i_max, id_j_max, max);

        printf("\n==========================================================================\n");
    }


// Освобождение памяти
    for (i = 0; i < n; i++){
        free(A[i]);
    }
    free(A);

    return 0;
}



















